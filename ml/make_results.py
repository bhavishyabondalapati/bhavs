"""Render ml/RESULTS.md from the JSON the benchmark and training runs wrote (numbers are never hand-typed)."""
import json
import math
from pathlib import Path

HERE = Path(__file__).parent
ART = HERE / "artifacts"
NAMES = {"popularity": "Popularity (baseline)", "als": "ALS (implicit)", "two_tower": "Two-tower (PyTorch)"}


def ci(p, n):
    return 1.96 * math.sqrt(max(p * (1 - p), 0) / max(n, 1))


def table(res):
    n = res["eval_users"]
    base = res["models"]["popularity"]["test"]["recall@10"]
    lines = ["| Model | recall@10 | 95% CI (±) | NDCG@10 | vs popularity | tuned settings |", "|---|---|---|---|---|---|"]
    for key in ("popularity", "als", "two_tower"):
        m = res["models"][key]
        t = m["test"]
        extra = ""
        if key == "two_tower":
            extra = f" (±{m['test_std']['recall@10']:.4f} over {m['seeds']} seeds)"
        params = ", ".join(f"{k}={v}" for k, v in m.get("params", {}).items()) or "-"
        lift = "-" if key == "popularity" else f"{t['recall@10'] / base:.2f}x"
        lines.append(f"| {NAMES[key]} | **{t['recall@10']:.4f}**{extra} | {ci(t['recall@10'], n):.4f} | {t['ndcg@10']:.4f} | {lift} | {params} |")
    return "\n".join(lines)


def main():
    parts = ["""# Recommender results

> **Two separate things are reported here. Do not mix them up.**
> 1. **MovieLens benchmark** (public data, thousands of users and items): this is where model quality is measured.
> 2. **bhavs production run** (17 titles, mostly *synthetic* viewers): this only produces the rows the website shows.
>    With a catalogue this small, recall@10 is not meaningful (10 of 17 titles is more than half the catalogue).

Numbers below are generated by `ml/make_results.py` from `ml/artifacts/*.json`. Reproduce with
`make ml-benchmark` (see README).
"""]
    results = [json.loads(p.read_text()) for p in sorted(ART.glob("results-*.json"))]
    parts.append("## 1. MovieLens benchmark\n")
    parts.append("""Data: MovieLens from [GroupLens](https://grouplens.org/datasets/movielens/) (F. Maxwell Harper and Joseph A. Konstan,
*The MovieLens Datasets: History and Context*, ACM TiiS 5(4), 2015). Used for research only and **not redistributed**:
`ml/data/` is gitignored. A *positive* is a rating of 4 or more.

**Split:** per-user temporal leave-last-out. Each user's positives are sorted by time; the **last** is the TEST item, the
second-to-last the VALIDATION item, everything earlier is TRAIN, so no future information reaches training.
**Metrics:** full ranking over every item the user has not interacted with (no sampled negatives). recall@10 is the share of
users whose held-out item is in their top 10 (with one held-out item this equals hit rate@10). NDCG@10 rewards ranking it
higher. Ties are counted against the model. Hyper-parameters were chosen on the validation item; the test item was scored
once. **The bar to beat is the popularity baseline** (same list for everyone).
""")
    best_name, best_score = "als", -1
    for r in results:
        parts.append(f"### {r['dataset']}\n")
        parts.append(f"{r['users']:,} users, {r['items']:,} items, {r['positives']:,} positives; {r['eval_users']:,} users evaluated; "
                     f"device `{r['device']}`; total benchmark time {r['total_seconds']} s.\n")
        parts.append(table(r) + "\n")
        for key in ("als", "two_tower"):
            sc = r["models"][key]["test"]["recall@10"]
            if sc > best_score + 1e-12 and r["users"] >= 5000:
                best_name, best_score = key, sc
    parts.append(f"**Model used for production rows:** `{best_name}` (best recall@10 on the largest dataset run).\n")
    (HERE / "best_model.txt").write_text(best_name + "\n")

    parts.append("## 2. bhavs production run (live rows on the website)\n")
    run = ART / "bhavs-run.json"
    if run.exists():
        s = json.loads(run.read_text())
        parts.append(f"""Last run: model `{s['model']}`, {s['users']} users, {s['titles']} titles, {s['interactions']} positive interactions,
{s['rows']} rows written to the `recommendations` table in {s['seconds']} s.

**Data caveat:** almost all of these users are **synthetic** (generated by `scripts/simulate_users`, clearly labelled
`synthetic-NNNN`); real users are the handful who signed up. The simulator itself has taste clusters, so the models
recovering them shows the pipeline works end to end; it says nothing about real-world quality.

Rows produced per user: **Top picks for you** (model scores, watched titles removed), up to two **Because you watched X**
rows (nearest titles to your recent favourites in the model's item space) and **Popular on bhavs**. Brand-new users get
the GLOBAL rows: overall popularity plus **popularity by genre** (cold start).
""")
        sc = s.get("sanity", {})
        if "popularity" in sc:
            parts.append(f"Offline sanity check on this synthetic data ({sc['eval_users']} users, {sc['n_items']} titles; same temporal split; "
                         "*not a benchmark*):\n\n| Model | recall@10 | NDCG@10 |\n|---|---|---|")
            for k in ("popularity", "als", "two_tower"):
                parts.append(f"| {NAMES[k]} | {sc[k]['recall@10']:.3f} | {sc[k]['ndcg@10']:.3f} |")
            parts.append("")
    else:
        parts.append("_No bhavs production run recorded yet. Run `make train`._\n")
    (HERE / "RESULTS.md").write_text("\n".join(parts))
    print("wrote RESULTS.md; best model:", best_name)


if __name__ == "__main__":
    main()
